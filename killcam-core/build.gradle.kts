// Pure JVM on purpose: the store, mock engine and server run unchanged in unit
// tests and in the desktop demo server, so the dashboard can be exercised
// without a phone. Everything Android-specific lives in :killcam.
java {
    toolchain { languageVersion.set(JavaLanguageVersion.of(17)) }
    withSourcesJar()
}

publishing {
    publications {
        register<MavenPublication>("maven") { from(components["java"]) }
    }
}

kotlin {
    jvmToolchain(17)
    explicitApi()
}

// KILLCAM_VERSION is generated from this build's version (gradle.properties' KILLCAM_VERSION, or the tag on JitPack),
// so /api/info, the dashboard and the HAR export always name the artifact that is running. Typed by hand, it still
// read 0.1.0 when 0.1.2 shipped.
val generateKillcamVersion by tasks.registering {
    val version = project.version.toString()
    val outDir = layout.buildDirectory.dir("generated/killcamVersion")
    inputs.property("version", version)
    outputs.dir(outDir)
    doLast {
        val file = outDir.get().file("com/krafton/killcam/core/KillcamVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |// Generated by killcam-core's generateKillcamVersion from the build's version. Do not edit.
            |package com.krafton.killcam.core
            |
            |/** This Killcam's version: the version its artifacts are published under. */
            |public const val KILLCAM_VERSION: String = "$version"
            |""".trimMargin(),
        )
    }
}
kotlin.sourceSets.named("main") { kotlin.srcDir(generateKillcamVersion) }

dependencies {
    api(libs.kotlinx.coroutines.core)
    api(libs.kotlinx.serialization.json)
    implementation(libs.ktor.server.cio)

    testImplementation(kotlin("test"))
    testImplementation(libs.junit)
}

tasks.test {
